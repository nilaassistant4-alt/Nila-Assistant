"""Acceptance tests: CONNECTORS screen (read-only view + guarded on/off).

Contract these tests rely on (HTTP, same bearer token as every other route):
  GET  /v1/connectors -> 200 {"ok":true,"connectors":[
         {"id","name","kind":"ai"|"integration","enabled":bool,"configured":bool,
          "state":"ready"|"needs_setup"|"off"|"blocked","reason":str,
          "hosts":[str], "usage": null | {"used":int,"allowed":int}} ]}
  POST /v1/connectors/<id>/enable   -> 200 {"ok":true,"connector":{...}}
  POST /v1/connectors/<id>/disable  -> 200 {"ok":true,"connector":{...}}
       Both need a FRESH step-up: `session.step_up_ok` must be true, and it is
       consumed by the call. Without it -> 403 and nothing changes.
  Unknown id -> 404. A locked vault -> 423.
  AI connector ids include: "ollama", "gemini", "openai", "anthropic".

Rules under test:
  1. Secrets (API keys) are NEVER returned, in any field.
  2. No payment / bank / card connector exists.
  3. `configured` follows the key; `state` says why something is not ready.
  4. Turning a connector off really stops its use; on/off needs a fresh step-up.
  5. Every toggle is audited, without any secret.
  6. Integrations are OFF by default.

Run:  python -m pytest tests/test_connectors_acceptance.py -q
Do not edit this file. If a test looks wrong, report it instead.
"""
from __future__ import annotations

import http.server
import json
import threading
import urllib.error
import urllib.request
from http.server import ThreadingHTTPServer

import pytest

from brain.agent.agent import Brain
from brain.api.gateway import Gateway, _Handler

TOKEN = "t" * 24
KEYS = {"GEMINI_API_KEY": "GEM-SECRET-AbCdEf123456", "OPENAI_API_KEY": "OAI-SECRET-ZyXwVu987654",
        "ANTHROPIC_API_KEY": "ANT-SECRET-QwErTy135790"}


@pytest.fixture()
def srv(config, vault, memory):
    gw = Gateway(config, vault, memory, token=TOKEN)
    _Handler.gateway = gw
    httpd = ThreadingHTTPServer(("127.0.0.1", 0), _Handler)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    yield httpd
    httpd.shutdown()
    httpd.server_close()


def call(httpd, path, body=None):
    req = urllib.request.Request(
        f"http://127.0.0.1:{httpd.server_port}{path}",
        data=json.dumps(body).encode() if body is not None else None,
        headers={"Authorization": f"Bearer {TOKEN}", "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=15) as r:
            return r.status, json.loads(r.read() or b"{}")
    except urllib.error.HTTPError as e:
        try:
            return e.code, json.loads(e.read() or b"{}")
        except Exception:
            return e.code, {}


def connectors(httpd):
    s, d = call(httpd, "/v1/connectors")
    assert s == 200, f"GET /v1/connectors -> {s}"
    return {c["id"]: c for c in d["connectors"]}


def toggle(httpd, vault, cid, action, step_up=True):
    vault.session.step_up_ok = bool(step_up)
    return call(httpd, f"/v1/connectors/{cid}/{action}", {})


class _Cloud:
    def __init__(self):
        self.requests = []
        outer = self

        class H(http.server.BaseHTTPRequestHandler):
            def log_message(self, *a):
                pass

            def do_POST(self):
                outer.requests.append(self.rfile.read(int(self.headers.get("Content-Length", 0))).decode("utf-8", "replace"))
                body = json.dumps({"candidates": [{"content": {"parts": [{"text": "public answer"}]}}],
                                   "usageMetadata": {"totalTokenCount": 5}}).encode()
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(body)

        self.srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), H)
        threading.Thread(target=self.srv.serve_forever, daemon=True).start()
        self.url = f"http://127.0.0.1:{self.srv.server_port}/v1beta"


# ------------------------------------------------------------------ what is listed
def test_the_four_ai_connectors_are_listed(srv):
    cs = connectors(srv)
    for cid in ("ollama", "gemini", "openai", "anthropic"):
        assert cid in cs and cs[cid]["kind"] == "ai", cid
    for c in cs.values():
        assert set(c) >= {"id", "name", "kind", "enabled", "configured", "state", "reason", "hosts", "usage"}
        assert isinstance(c["hosts"], list) and c["state"] in ("ready", "needs_setup", "off", "blocked")


def test_no_payment_or_bank_connector_exists(srv):
    banned = ("stripe", "paypal", "razorpay", "paytm", "phonepe", "bank", "card", "upi", "payment", "wallet")
    for c in connectors(srv).values():
        label = (c["id"] + " " + c["name"]).lower()
        assert not any(b in label for b in banned), f"payment/bank connector listed: {label}"


def test_integrations_are_off_by_default(srv):
    for c in connectors(srv).values():
        if c["kind"] == "integration":
            assert c["enabled"] is False and c["state"] in ("off", "needs_setup"), c["id"]


# ------------------------------------------------------------------ secrets
def test_api_keys_never_appear_in_the_response(srv, monkeypatch):
    for k, v in KEYS.items():
        monkeypatch.setenv(k, v)
    s, d = call(srv, "/v1/connectors")
    text = json.dumps(d)
    for v in KEYS.values():
        assert v not in text and v[:8] not in text, "a key (or its start) leaked into /v1/connectors"


def test_configured_follows_the_key(srv, monkeypatch):
    monkeypatch.delenv("GEMINI_API_KEY", raising=False)
    g = connectors(srv)["gemini"]
    assert g["configured"] is False and g["state"] == "needs_setup" and g["reason"]
    monkeypatch.setenv("GEMINI_API_KEY", KEYS["GEMINI_API_KEY"])
    assert connectors(srv)["gemini"]["configured"] is True


# ------------------------------------------------------------------ guarded on/off
def test_toggle_needs_a_fresh_step_up_and_consumes_it(srv, vault, monkeypatch):
    monkeypatch.setenv("GEMINI_API_KEY", KEYS["GEMINI_API_KEY"])
    assert connectors(srv)["gemini"]["enabled"] is True
    s, _ = toggle(srv, vault, "gemini", "disable", step_up=False)
    assert s == 403 and connectors(srv)["gemini"]["enabled"] is True, "no step-up: nothing may change"
    s, d = toggle(srv, vault, "gemini", "disable", step_up=True)
    assert s == 200 and d["connector"]["enabled"] is False and connectors(srv)["gemini"]["state"] == "off"
    s, _ = call(srv, "/v1/connectors/gemini/enable", {})
    assert s == 403, "the step-up was consumed by the previous call"
    s, d = toggle(srv, vault, "gemini", "enable", step_up=True)
    assert s == 200 and connectors(srv)["gemini"]["enabled"] is True


def test_unknown_connector_is_404(srv, vault):
    s, _ = toggle(srv, vault, "no-such-connector", "enable")
    assert s == 404


def test_locked_vault_is_refused(srv, vault):
    vault.lock()
    assert call(srv, "/v1/connectors")[0] == 423


# ------------------------------------------------------------------ off really means off
def test_a_disabled_provider_is_not_used_online(srv, config, vault, memory, monkeypatch):
    cloud = _Cloud()
    monkeypatch.setenv("GEMINI_API_KEY", KEYS["GEMINI_API_KEY"])
    config.agent.update({"online_base_url": cloud.url, "online_daily_requests": 100, "online_rpm": 100})
    brain = Brain(config, vault, memory)
    brain.handle("three names for a tea shop", mode="online")
    assert len(cloud.requests) == 1, "enabled provider should be used"
    assert connectors(srv)["gemini"]["usage"]["used"] == 1
    assert toggle(srv, vault, "gemini", "disable")[0] == 200
    turn = Brain(config, vault, memory).handle("three more names", mode="online")
    assert len(cloud.requests) == 1, "a disabled provider must never be called"
    assert turn.route["where"] != "online" and turn.route.get("notice")
    assert toggle(srv, vault, "gemini", "enable")[0] == 200
    Brain(config, vault, memory).handle("one more name", mode="online")
    assert len(cloud.requests) == 2
    cloud.srv.shutdown()


# ------------------------------------------------------------------ audit
def test_toggles_are_audited_without_secrets(srv, vault, monkeypatch):
    monkeypatch.setenv("GEMINI_API_KEY", KEYS["GEMINI_API_KEY"])
    toggle(srv, vault, "gemini", "disable")
    toggle(srv, vault, "gemini", "enable")
    entries = vault.read_audit(300)
    events = [str(e.get("event", "")) for e in entries]
    assert sum("connector" in ev for ev in events) >= 2, f"each toggle must be audited: {events[-10:]}"
    blob = json.dumps(entries)
    assert not any(v in blob or v[:8] in blob for v in KEYS.values())
